const SymGlyph = ({ type, x, y, color = "#cbd5e1", fill = "#0f172a" }) => {
  if (type === "process")
    // 加工：○
    return <circle cx={x} cy={y} r="17" fill={fill} stroke={color} strokeWidth="2.5" />;
  if (type === "transport")
    // 運搬：⇒（右向き太矢印）
    return (
      <polygon
        points={`${x - 16},${y - 7} ${x + 3},${y - 7} ${x + 3},${y - 14} ${x + 18},${y} ${x + 3},${y + 14} ${x + 3},${y + 7} ${x - 16},${y + 7}`}
        fill={fill}
        stroke={color}
        strokeWidth="2.5"
        strokeLinejoin="round"
      />
    );
  if (type === "delay")
    // 滞留：D
    return (
      <path
        d={`M ${x - 11} ${y - 17} L ${x - 11} ${y + 17} A 17 17 0 0 0 ${x - 11} ${y - 17} Z`}
        fill={fill}
        stroke={color}
        strokeWidth="2.5"
        strokeLinejoin="round"
      />
    );
  if (type === "qcheck")
    // 品質検査：◇
    return (
      <polygon
        points={`${x},${y - 18} ${x + 18},${y} ${x},${y + 18} ${x - 18},${y}`}
        fill={fill}
        stroke={color}
        strokeWidth="2.5"
        strokeLinejoin="round"
      />
    );
  if (type === "ncheck")
    // 数量検査：□
    return (
      <rect x={x - 15} y={y - 15} width="30" height="30" fill={fill} stroke={color} strokeWidth="2.5" />
    );
  if (type === "store")
    // 貯蔵：▽
    return (
      <polygon
        points={`${x - 17},${y - 15} ${x + 17},${y - 15} ${x},${y + 18}`}
        fill={fill}
        stroke={color}
        strokeWidth="2.5"
        strokeLinejoin="round"
      />
    );
  return null;
};

